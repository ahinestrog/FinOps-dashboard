/** Registro crudo tal y como lo entrega CloudTrail, para el modal de evento. */
export function buildEventRecord(event: TrailEvent): Record<string, unknown> {
  return {
    eventVersion: '1.09',
    eventTime: `2026-08-04T${event.time}Z`,
    eventSource: event.eventSource,
    eventName: event.eventName,
    awsRegion: event.region,
    sourceIPAddress: event.sourceIp,
    userAgent: 'aws-cli/2.15.4 Python/3.11',
    userIdentity: {
      type: event.identity.startsWith('role/') ? 'AssumedRole' : 'IAMUser',
      arn: `arn:aws:iam::447188208820:${event.identity}`,
      accountId: '447188208820',
    },
    requestParameters: { instanceType: 'm6i.4xlarge', maxCount: 4, minCount: 4 },
    responseElements: { requestId: '8f31c0b2-4d19-4a77-9e0f-2b1c7a55e3d1' },
    readOnly: !event.isWrite,
    managementEvent: true,
    eventCategory: 'Management',
    ...(event.result === 'Success' ? {} : { errorCode: event.result }),
  }
}
